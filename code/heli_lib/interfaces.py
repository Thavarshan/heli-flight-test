"""Provisional adapter boundary. Implementations must document frames and units."""
from typing import Protocol, Mapping, Any

class Simulator(Protocol):
    def reset(self, *, seed: int, configuration: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def step(self, controls: Mapping[str, float], dt_s: float) -> Mapping[str, Any]: ...
    def close(self) -> None: ...
